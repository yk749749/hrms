class Command(BaseCommand):
    help = "预置 AI 制度知识库条目（按标题幂等写入，可重复执行）"

    @transaction.atomic
    def handle(self, *args, **options):
        created_count = 0
        for category, title, content in KNOWLEDGE_DEFS:
            _, created = models.Knowledge.objects.update_or_create(
                title=title,
                defaults={"category": category, "content": content},
            )
            created_count += int(created)

        total = models.Knowledge.objects.count()
        self.stdout.write(
            self.style.SUCCESS(
                f"知识库同步完成：定义 {len(KNOWLEDGE_DEFS)} 条，本次新增 {created_count} 条，当前共 {total} 条"
            )
        )
