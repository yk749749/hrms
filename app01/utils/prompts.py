# app01/utils/prompts.py
"""提示词模板：统一采用“角色 + 要求 + 输出格式”三段式（T2）。

为什么集中在一个模块里：提示词是本项目最需要反复调的东西，单独放一处，
答辩时可以直接展示“改提示词就能改效果”，也避免散落在各个视图里。
"""

# ---------------------------------------------------------------------------
# 模块 A：招聘 JD
# ---------------------------------------------------------------------------
JD_SYSTEM = (
    "你是一名有 10 年经验的企业 HR，擅长用简洁、专业、有吸引力的中文写招聘文案；"
    "只写岗位真正需要的信息，不夸大、不承诺资料里没有的待遇。"
)


def build_jd_prompt(title, department=""):
    """为指定岗位构造生成 JD 的提示词（三段式）。"""
    dept = f"所属部门：{department}。" if department else ""
    return (
        "【角色】你是一名资深 HR，负责为公司撰写招聘文案。\n"
        f"【要求】为「{title}」岗位写一份招聘 JD。{dept}"
        "职责与要求要贴合岗位本身，不要堆砌空话；薪资只给区间，不写具体承诺。\n"
        "【输出格式】按下面三段顺序输出，不要使用 Markdown 表格：\n"
        "岗位职责：\n"
        "1. （4 条，每条不超过 18 字）\n"
        "任职要求：\n"
        "1. （4 条，每条不超过 18 字）\n"
        "薪资范围：\n"
        "月薪 X-XK，另加绩效奖金。\n"
        "全文控制在 220 字以内。"
    )


# ---------------------------------------------------------------------------
# 模块 B：制度知识库问答（简化版 RAG）
# ---------------------------------------------------------------------------
QA_SYSTEM = (
    "你是一名企业制度助手。你只能依据用户给出的【资料】回答；"
    "资料里没有的信息一律回答“不知道”，严禁编造制度条款、金额、流程或审批人。"
    "回答简洁、口语化，先给结论，再给依据。"
)


def build_qa_prompt(question, context):
    """把检索到的资料拼进提示词，让模型“照着资料回答”。"""
    return (
        "【资料】\n"
        f"{context}\n\n"
        "【问题】\n"
        f"{question}\n\n"
        "【输出格式】\n"
        "1. 第一段：用一两句话直接回答问题；\n"
        "2. 第二段：列出 1-3 条依据，并注明出自哪份制度（用《》标出制度名）；\n"
        "3. 若资料未覆盖该问题，只回答“不知道”，并提示可联系人事部门确认。"
    )


# ---------------------------------------------------------------------------
# 模块 C：数据智能点评（考勤 + 薪资）
# ---------------------------------------------------------------------------
COMMENT_SYSTEM = (
    "你是一名客观、专业的人力资源数据分析师，只根据给定的数据说话，"
    "不臆测未提供的信息，不评价员工人品，不做法律或薪酬合规判断。"
)


def build_data_comment_prompt(data_text):
    """对“某员工某月”的考勤与薪资数据生成点评。"""
    return (
        "【数据】\n"
        f"{data_text}\n\n"
        "【要求】\n"
        "1. 先概括该员工本月的出勤与薪资表现（有异常要指出来）；\n"
        "2. 再给一条具体、可执行的改进建议；\n"
        "3. 语气客观中立，不说教、不夸大。\n"
        "【输出格式】\n"
        "第一行以「点评：」开头，第二行以「建议：」开头，总字数不超过 80 字。"
    )


